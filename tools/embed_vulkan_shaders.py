#!/usr/bin/env python3
"""Fail-closed, deterministic Vulkan 1.0 SPIR-V embedding.

The Vulkan dialect lives in shaders_vk/, independent of GLES's shaders/. With no
compiler, --check fails and regeneration never touches the checked-in table. In
particular, missing glslc can NEVER replace working SPIR-V with an empty table.
"""
import argparse
from pathlib import Path
import re
import shutil
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / "native/src/render/shaders_vk"
OUTPUT = ROOT / "native/src/render/af_shaders_vk.h"
REQUIRED = {
    ("forward", "vert"), ("forward", "frag"),
    ("shadow", "vert"), ("shadow", "frag"),
    ("ground", "vert"), ("ground", "frag"),
    ("line", "vert"), ("line", "frag"),
    ("fullscreen", "vert"), ("bloom_down", "frag"),
    ("bloom_up", "frag"), ("composite", "frag"),
    ("forward_plus", "comp"),
}
ENUM = {"vert": "AF_STAGE_VERT", "frag": "AF_STAGE_FRAG", "comp": "AF_STAGE_COMP"}


def compiler():
    import os
    explicit = os.environ.get("AF_GLSLC")
    if explicit:
        if not Path(explicit).is_file():
            raise RuntimeError(f"AF_GLSLC does not name a file: {explicit}")
        return explicit
    ndk = os.environ.get("ANDROID_NDK") or os.environ.get("ANDROID_NDK_HOME")
    if ndk:
        candidate = Path(ndk) / "shader-tools/linux-x86_64/glslc"
        if candidate.is_file():
            return str(candidate)
    return shutil.which("glslc")


def inline(path, stack=()):
    path = path.resolve()
    if path in stack:
        raise RuntimeError(f"shader include cycle: {path}")
    result = []
    for line in path.read_text(encoding="utf-8").splitlines(True):
        match = re.match(r'\s*#include\s+"([^"]+)"', line)
        result.append(inline(path.parent / match.group(1), stack + (path,)) if match else line)
    return "".join(result)


def source(path, stage):
    # Same dialect, compiler switches and optimisation as the checked-in Vulkan-era table.
    header = "#version 450\n"
    if stage == "vert":
        header += "#define AF_STAGE_VERTEX 1\n"
    return header + "#define AF_VULKAN 1\n" + inline(path)


def embed(entries):
    out = ["/*\n * af_shaders_vk.h -- GENERATED by tools/embed_vulkan_shaders.py. Do not edit.\n"
           " *\n * SPIR-V words for the Vulkan backend. Each array is a complete shader module; the\n"
           " * table pairs a pipeline name with a stage so af_shaders.cpp can look one up by name.\n"
           " */\n#ifndef AF_SHADERS_VK_H\n#define AF_SHADERS_VK_H\n\n",
           '#include "af_shaders.h"\n\nnamespace af {\nnamespace shaders_vk {\n\n']
    for (name, stage), words in entries:
        out.append("static const uint32_t kSpv_%s_%s[%d] = {\n" % (name, stage, len(words)))
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",\n")
        out.append("};\n\n")
    out.append("static const AfShaderVk kTable[] = {\n")
    for (name, stage), words in entries:
        out.append('    {"%s", %s, kSpv_%s_%s, %du},\n'
                   % (name, stage, ENUM[stage], name, stage, len(words)))
    out.append("};\n\n} /* namespace shaders_vk */\n} /* namespace af */\n\n#endif\n")
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compile and reject stale embedded SPIR-V")
    args = parser.parse_args()
    stages = sorted((p.stem, p.suffix[1:], p) for p in SHADERS.iterdir()
                    if p.suffix in (".vert", ".frag", ".comp"))
    keys = {(name, stage) for name, stage, _ in stages}
    if len(keys) != len(stages) or keys != REQUIRED:
        raise RuntimeError(f"Vulkan stage set mismatch: missing={sorted(REQUIRED-keys)}, unexpected={sorted(keys-REQUIRED)}")
    glslc = compiler()
    if not glslc:
        raise RuntimeError("Vulkan SPIR-V requires glslc; checked-in modules were NOT regenerated or validated")
    validator = Path(glslc).parent / "spirv-val"
    entries = []
    with tempfile.TemporaryDirectory(prefix="af-vulkan-") as directory:
        for name, stage, path in stages:
            stage_path = Path(directory) / f"{name}.{stage}"
            output = Path(directory) / f"{name}.{stage}.spv"
            stage_path.write_text(source(path, stage), encoding="utf-8")
            command = [glslc, f"-fshader-stage={stage}", "-O", "--target-env=vulkan1.0", "-Werror",
                       "-o", str(output), str(stage_path)]
            result = subprocess.run(command, capture_output=True, text=True)
            if result.returncode:
                raise RuntimeError(f"Vulkan compile failed: {name}.{stage}\n{result.stdout}{result.stderr}")
            if validator.is_file():
                result = subprocess.run([str(validator), "--target-env", "vulkan1.0", str(output)],
                                        capture_output=True, text=True)
                if result.returncode:
                    raise RuntimeError(f"spirv-val rejected {name}.{stage}: {result.stdout}{result.stderr}")
            blob = output.read_bytes()
            if len(blob) % 4 or blob[:4] != b"\x03\x02\x23\x07":
                raise RuntimeError(f"invalid SPIR-V header: {name}.{stage}")
            words = struct.unpack("<%dI" % (len(blob) // 4), blob)
            entries.append(((name, stage), words))
            print(f"  PASS {name}.{stage}: {len(words)} words")
    table = embed(entries)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != table:
            raise RuntimeError("embedded Vulkan table is stale; run tools/embed_vulkan_shaders.py")
        print(f"PASS: {len(entries)} Vulkan stages compiled and embedded table matches")
    else:
        OUTPUT.write_text(table, encoding="utf-8")
        print(f"Embedded {len(entries)} Vulkan stages")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as error:
        raise SystemExit(str(error))
