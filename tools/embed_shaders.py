#!/usr/bin/env python3
"""Embed and optionally compile the complete GLES 3.1 shader set.

Default: deterministic text embedding, with no external tools required.
--check: require glslc, compile every stage and verify the checked-in table is current.
Missing, duplicate or unexpected stages are errors, never a partial renderer.
"""
import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / "native/src/render/shaders"
OUTPUT = ROOT / "native/src/render/af_shaders_gl.h"
REQUIRED = {
    ("forward", "vert"), ("forward", "frag"),
    ("shadow", "vert"), ("shadow", "frag"),
    ("ground", "vert"), ("ground", "frag"),
    ("line", "vert"), ("line", "frag"),
    ("fullscreen", "vert"), ("bloom_down", "frag"),
    ("bloom_up", "frag"), ("composite", "frag"),
}
ENUM = {"vert": "AF_STAGE_VERT", "frag": "AF_STAGE_FRAG"}


def find_compiler():
    explicit = os.environ.get("AF_GLSLC")
    if explicit:
        if not Path(explicit).is_file():
            raise RuntimeError(f"AF_GLSLC does not name a file: {explicit}")
        return explicit
    ndk = os.environ.get("ANDROID_NDK") or os.environ.get("ANDROID_NDK_HOME")
    if ndk:
        candidate = Path(ndk) / "shader-tools/linux-x86_64/glslc"
        if candidate.is_file():
            return str(candidate)
    return shutil.which("glslc")


def inline(path, stack=()):
    path = path.resolve()
    if path in stack:
        raise RuntimeError(f"shader include cycle: {path}")
    result = []
    for line in path.read_text(encoding="utf-8").splitlines(True):
        match = re.match(r'\s*#include\s+"([^"]+)"', line)
        if match:
            result.append(inline(path.parent / match.group(1), stack + (path,)))
        else:
            result.append(line)
    return "".join(result)


def source(path, stage):
    header = "#version 310 es\n"
    if stage == "vert":
        header += "#define AF_STAGE_VERTEX 1\n"
    header += "precision highp float;\nprecision highp int;\nprecision highp sampler2D;\n"
    return header + inline(path)


def c_string(text):
    lines = []
    for line in text.splitlines(True):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t")
        escaped = escaped.replace("\r", "").replace("\n", "\\n")
        lines.append('    "' + escaped + '"\n')
    return "".join(lines)


def emit(entries):
    out = ["/* GENERATED by tools/embed_shaders.py. Do not edit.\n"
           " * Complete GLES 3.1 shader table; no alternate graphics API. */\n",
           "#ifndef AF_SHADERS_GL_H\n#define AF_SHADERS_GL_H\n\n",
           '#include "af_shaders.h"\n\nnamespace af {\nnamespace shaders_gl {\n\n']
    for (name, stage), text in entries:
        out.append(f"static const char kSrc_{name}_{stage}[] =\n" + c_string(text) + ";\n\n")
    out.append("static const AfShaderGl kTable[] = {\n")
    for (name, stage), _ in entries:
        out.append(f'    {{"{name}", {ENUM[stage]}, kSrc_{name}_{stage}}},\n')
    out.append("};\n\n} /* namespace shaders_gl */\n} /* namespace af */\n\n#endif\n")
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="require compiler and reject stale table")
    args = parser.parse_args()
    stages = sorted((p.stem, p.suffix[1:], p) for p in SHADERS.iterdir() if p.suffix in (".vert", ".frag", ".comp"))
    keys = {(name, stage) for name, stage, _ in stages}
    if len(keys) != len(stages) or keys != REQUIRED:
        raise RuntimeError(f"GLES stage set mismatch: missing={sorted(REQUIRED-keys)}, unexpected={sorted(keys-REQUIRED)}")
    compiler = find_compiler()
    if args.check and not compiler:
        raise RuntimeError("--check requires glslc; no compiler validation is claimed")
    entries = [((name, stage), source(path, stage)) for name, stage, path in stages]
    if compiler:
        with tempfile.TemporaryDirectory(prefix="af-gles-") as directory:
            for (name, stage), text in entries:
                path = Path(directory) / f"{name}.{stage}"
                path.write_text(text, encoding="utf-8")
                result = subprocess.run([compiler, f"-fshader-stage={stage}", "--target-env=opengl", "-Werror", "-o", os.devnull, str(path)], capture_output=True, text=True)
                if result.returncode:
                    raise RuntimeError(f"GLES compile failed: {name}.{stage}\n{result.stdout}{result.stderr}")
                print(f"  PASS {name}.{stage}")
    table = emit(entries)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != table:
            raise RuntimeError("embedded GLES table is stale; run tools/embed_shaders.py")
        print(f"PASS: all {len(entries)} GLES stages compiled; embedded table matches")
    else:
        OUTPUT.write_text(table, encoding="utf-8")
        print(f"Embedded {len(entries)} GLES stages; compiler {'validated' if compiler else 'not run (text embedding only)'}")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as error:
        raise SystemExit(str(error))
